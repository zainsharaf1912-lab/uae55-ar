// Headless smoke test: runs the real app (UI + director + interactions) against the three.js test double.
// Usage: node tests/run-headless.js <siteDir> <outDir>
const { chromium } = require('/opt/npm-tools/node_modules/playwright');
const path = require('path');
const [site, out] = process.argv.slice(2);
(async () => {
  const errors = [], logs = [];
  const b = await chromium.launch();
  const p = await b.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1, hasTouch: true, isMobile: true });
  p.on('console', m => { const t = m.text(); if (m.type() === 'error') errors.push(t); else logs.push(m.type() + ': ' + t); });
  p.on('pageerror', e => errors.push('PAGEERROR ' + e.message + '\n' + e.stack));
  p.on('requestfailed', r => errors.push('REQFAIL ' + r.url() + ' ' + (r.failure() && r.failure().errorText)));
  await p.goto(site + '/index.html');
  await p.waitForFunction(() => window.__uae55 && window.__uae55.ready, null, { timeout: 15000 }).catch(e => errors.push('NOT READY: ' + e.message));
  await p.waitForTimeout(500);
  await p.screenshot({ path: path.join(out, '01-splash.png'), fullPage: true });
  await p.click('#btn-start-3d');
  await p.waitForTimeout(1200);
  await p.screenshot({ path: path.join(out, '02-scene1.png') });
  const app = 'window.__uae55';
  const step = async (label, js, wait = 600) => { try { await p.evaluate(js); } catch (e) { errors.push(label + ': ' + e.message); } await p.waitForTimeout(wait); };
  await step('hotspot barjeel', `${app}.director.handleTap('hs:barjeel')`);
  await p.screenshot({ path: path.join(out, '03-sheet.png') });
  await step('close sheet', `document.getElementById('sheet-close').click()`);
  await step('door', `${app}.director.handleTap('door')`, 2500);
  const s2 = await p.evaluate(`${app}.director.index`); logs.push('after door scene index=' + s2);
  await step('hs father', `${app}.director.handleTap('hs:father')`, 2200);
  await step('oyster', `${app}.director.handleTap('oyster')`, 2200);
  await step('pearl', `${app}.director.handleTap('pearl')`, 800);
  await p.screenshot({ path: path.join(out, '04-pearl.png') });
  await step('next', `document.getElementById('btn-next').click()`, 2200);
  await step('basket', `${app}.director.handleTap('basket')`, 600);
  for (let k = 0; k < 4; k++) await step('step ' + k, `document.querySelectorAll('.steps-tabs button')[${k}].click()`, 300);
  await p.screenshot({ path: path.join(out, '05-weaving-steps.png') });
  await step('close', `document.getElementById('sheet-close').click()`);
  await step('next', `document.getElementById('btn-next').click()`, 2200);
  await step('grandma', `${app}.director.handleTap('grandma')`, 800);
  await step('close', `document.getElementById('sheet-close').click()`);
  await step('next', `document.getElementById('btn-next').click()`, 2200);
  await step('tv', `${app}.director.handleTap('tv')`, 2500);
  const tvPlaying = await p.evaluate(`${app}.tvProgram.playing`); logs.push('tv playing=' + tvPlaying);
  await p.evaluate(`document.body.appendChild(Object.assign(${app}.tvProgram.canvas, {id:'tvdbg', style:'position:fixed;left:0;top:0;width:256px;z-index:99'}))`);
  await p.screenshot({ path: path.join(out, '06-tv-canvas.png') });
  await p.evaluate(`document.getElementById('tvdbg').remove()`);
  await p.waitForTimeout(19000);
  const tvAfter = await p.evaluate(`${app}.tvProgram.playing`); logs.push('tv playing after program=' + tvAfter);
  await step('close', `document.getElementById('sheet-close').click()`);
  await step('next', `document.getElementById('btn-next').click()`, 9500);
  const finaleShown = await p.evaluate(`document.getElementById('finale').classList.contains('is-active')`); logs.push('finale shown=' + finaleShown);
  await p.screenshot({ path: path.join(out, '07-finale.png'), fullPage: true });
  await step('restart', `document.getElementById('btn-restart').click()`, 2500);
  const back = await p.evaluate(`${app}.director.index`); logs.push('after restart index=' + back);
  await step('menu goto 5', `${app}.ui.emit('goto', 4)`, 2200);
  await step('menu goto 7', `${app}.ui.emit('goto', 6)`, 1500);
  await step('menu goto 1 mid-finale', `${app}.ui.emit('goto', 0)`, 2500);
  await step('exit', `document.getElementById('btn-exit').click()`, 500);
  const onSplash = await p.evaluate(`document.getElementById('splash').classList.contains('is-active')`); logs.push('exit to splash=' + onSplash);
  console.log('--- LOGS ---\n' + logs.join('\n'));
  console.log('--- ERRORS (' + errors.length + ') ---\n' + errors.join('\n'));
  await b.close();
})();
