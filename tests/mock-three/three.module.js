let loopErrors = 0;
export function WebGLRenderer() {
  const r = auto('renderer');
  r.xr = auto('xr'); r.xr.isPresenting = false;
  r.setAnimationLoop = fn => {
    const tick = () => { try { fn(performance.now(), null); } catch (e) { if (loopErrors++ < 5) console.error('LOOP ERROR: ' + e.message + '\n' + e.stack); } requestAnimationFrame(tick); };
    requestAnimationFrame(tick);
  };
  window.__mockRenderer = r;
  return r;
}
